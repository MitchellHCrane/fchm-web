/**
 * Generates public/_redirects — the Netlify host-based routing that makes the
 * one static deploy behave like ~25 separate subdomain sites.
 *
 * Runs before `next dev` and `next build` (see package.json pre* scripts).
 *
 * For each officer:
 *   https://<slug>.1stclasshomemortgage.com/*  ->  /sites/<slug>/:splat   200
 * plus explicit rules so /robots.txt and /sitemap.xml resolve to the per-slug
 * files, and a 301 for any officer with `redirectTo`.
 */
// Run with `tsx` (see package.json) so the .ts officer records import directly.
import { readdirSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join, resolve } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");

const DOMAIN = "1stclasshomemortgage.com";
const officersDir = join(root, "packages/content/officers");

const files = readdirSync(officersDir).filter(
  (f) => f.endsWith(".ts") && f !== "index.ts" && f !== "_template.ts",
);

const officers = [];
for (const f of files) {
  const mod = await import(pathToFileURL(join(officersDir, f)).href);
  officers.push(mod.default);
}
officers.sort((a, b) => a.slug.localeCompare(b.slug));

const lines = [
  "# GENERATED by scripts/gen-redirects.mjs — do not edit by hand.",
  "# Netlify host-based routing: one static deploy -> many subdomain sites.",
  "",
  "# Shared static assets MUST be matched (and served as-is) before any of the",
  "# per-host `/*` catch-alls below, on every host, or a request like",
  "# https://andrew.1stclasshomemortgage.com/_next/static/css/xxx.css gets",
  "# force-rewritten to /sites/andrew/_next/static/css/xxx.css — which doesn't",
  "# exist — 404ing every CSS/JS asset and every officer's headshot/icons.",
  "# (Netlify's `!` force flag makes a redirect win over an existing static",
  "# file, which is exactly what breaks these unless they're matched first.)",
  "/_next/*        /_next/:splat        200!",
  "/headshots/*    /headshots/:splat    200!",
  "/icons/*        /icons/:splat        200!",
  "/backgrounds/*  /backgrounds/:splat  200!",
  "/brand/*        /brand/:splat        200!",
  "/company/*      /company/:splat      200!",
  "/dpa/*          /dpa/:splat          200!",
  "/referral/*     /referral/:splat     200!",
  "/docs/*         /docs/:splat         200!",
  "",
];

let live = 0;
for (const o of officers) {
  const host = `https://${o.slug}.${DOMAIN}`;

  if (o.redirectTo) {
    lines.push(
      `# ${o.slug} -> ${o.redirectTo} (consolidated)`,
      `${host}/*  https://${o.redirectTo}.${DOMAIN}/:splat  301!`,
      "",
    );
    continue;
  }

  // Retired officers: no site to serve, but if the subdomain is still (or
  // ever becomes) DNS-live, send visitors/crawlers to the homepage instead
  // of leaving them to 404.
  if (o.status === "retired") {
    lines.push(
      `# ${o.name} (retired -> home)`,
      `${host}/*  https://${DOMAIN}/  301!`,
      "",
    );
    continue;
  }

  // Only `live` officers get a public subdomain. Drafts still build at
  // /sites/<slug>/ for preview but aren't routed.
  if (o.status !== "live") continue;
  live++;

  lines.push(
    `# ${o.name}`,
    `${host}/robots.txt   /sites/${o.slug}/robots.txt   200!`,
    `${host}/sitemap.xml  /sites/${o.slug}/sitemap.xml  200!`,
    `${host}/*            /sites/${o.slug}/:splat        200!`,
    "",
  );
}

// --- Tier 2/3: microsites + company (Phase 4/5) -----------------------------
// These aren't per-officer data files, so the host list is static here.
lines.push(
  "# Tier 2 — microsites",
  `https://referral.${DOMAIN}/robots.txt   /referral/robots.txt   200!`,
  `https://referral.${DOMAIN}/sitemap.xml  /referral/sitemap.xml  200!`,
  `https://referral.${DOMAIN}/*            /referral/:splat        200!`,
  "",
  `https://dpa.${DOMAIN}/robots.txt   /dpa/robots.txt   200!`,
  `https://dpa.${DOMAIN}/sitemap.xml  /dpa/sitemap.xml  200!`,
  `https://dpa.${DOMAIN}/*            /dpa/:splat        200!`,
  "",
  "# Tier 3 — company (both apex domains, from one build)",
  `https://${DOMAIN}/robots.txt   /company/1stclasshomemortgage/robots.txt   200!`,
  `https://${DOMAIN}/sitemap.xml  /company/1stclasshomemortgage/sitemap.xml  200!`,
  `https://${DOMAIN}/*            /company/1stclasshomemortgage/:splat        200!`,
  "",
  "https://firstclasshomemortgage.com/robots.txt   /company/firstclasshomemortgage/robots.txt   200!",
  "https://firstclasshomemortgage.com/sitemap.xml  /company/firstclasshomemortgage/sitemap.xml  200!",
  "https://firstclasshomemortgage.com/*            /company/firstclasshomemortgage/:splat        200!",
  "",
);

await writeFile(join(root, "public/_redirects"), lines.join("\n"), "utf8");
console.log(
  `gen-redirects: wrote public/_redirects — ${live} live officer host block(s), ` +
    `${officers.filter((o) => o.redirectTo).length} consolidation 301(s), ` +
    `${officers.length} officer file(s) scanned, ` +
    `+ referral/dpa/company (Tier 2/3, static).`,
);
