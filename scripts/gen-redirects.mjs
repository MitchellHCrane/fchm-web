/**
 * Generates public/_redirects — the Netlify host-based routing that makes the
 * one static deploy behave like ~25 separate subdomain sites.
 *
 * Runs before `next dev` and `next build` (see package.json pre* scripts).
 *
 * For each officer:
 *   https://<slug>.1stclasshomemortgage.com/*  ->  /sites/<slug>/:splat   200
 * plus explicit rules so /robots.txt and /sitemap.xml resolve to the per-slug
 * files, and a 301 for any officer with `redirectTo`.
 */
// Run with `tsx` (see package.json) so the .ts officer records import directly.
import { readdirSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join, resolve } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");

const DOMAIN = "1stclasshomemortgage.com";
const officersDir = join(root, "packages/content/officers");

const files = readdirSync(officersDir).filter(
  (f) => f.endsWith(".ts") && f !== "index.ts" && f !== "_template.ts",
);

const officers = [];
for (const f of files) {
  const mod = await import(pathToFileURL(join(officersDir, f)).href);
  officers.push(mod.default);
}
officers.sort((a, b) => a.slug.localeCompare(b.slug));

const lines = [
  "# GENERATED by scripts/gen-redirects.mjs — do not edit by hand.",
  "# Netlify host-based routing: one static deploy -> many subdomain sites.",
  "",
];

let live = 0;
for (const o of officers) {
  const host = `https://${o.slug}.${DOMAIN}`;

  if (o.redirectTo) {
    lines.push(
      `# ${o.slug} -> ${o.redirectTo} (consolidated)`,
      `${host}/*  https://${o.redirectTo}.${DOMAIN}/:splat  301!`,
      "",
    );
    continue;
  }

  // Only `live` officers get a public subdomain. Drafts still build at
  // /sites/<slug>/ for preview but aren't routed.
  if (o.status !== "live") continue;
  live++;

  lines.push(
    `# ${o.name}`,
    `${host}/robots.txt   /sites/${o.slug}/robots.txt   200!`,
    `${host}/sitemap.xml  /sites/${o.slug}/sitemap.xml  200!`,
    `${host}/*            /sites/${o.slug}/:splat        200!`,
    "",
  );
}

await writeFile(join(root, "public/_redirects"), lines.join("\n"), "utf8");
console.log(
  `gen-redirects: wrote public/_redirects — ${live} live host block(s), ` +
    `${officers.filter((o) => o.redirectTo).length} consolidation 301(s), ` +
    `${officers.length} file(s) scanned.`,
);
